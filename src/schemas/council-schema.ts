/**
 * Council collections — teams, membership, invites, decisions, options,
 * votes and arguments.
 *
 * Tenant isolation uses DeepSpace's native `'team'` permission level:
 * every collection carries a `teamId` column named by `teamField`, and the
 * RecordRoom resolves membership from the `team_members` collection
 * (`teamId`, `userId`, `status`; a row counts when status is 'active' or
 * null). A user therefore only ever receives rows for teams they belong to
 * (plus rows they created themselves — that is how `'team'` is defined).
 *
 * Clients get READ access only. Every write goes through a server action in
 * src/actions/, which checks team membership and team role before touching
 * the data. That is deliberate: RBAC `create` is a plain boolean, so a
 * client-side create could set `teamId` to a team the caller isn't in.
 */

import type { CollectionSchema, RolePermissions } from 'deepspace/schema'

/** Read rows of my teams; never write directly (actions do the writing). */
const TEAM_READ_ONLY: RolePermissions = {
  read: 'team',
  create: false,
  update: false,
  delete: false,
}

/** Same rule for every role, including app admins: team data stays in-team. */
const teamScoped = {
  '*': TEAM_READ_ONLY,
  viewer: TEAM_READ_ONLY,
  member: TEAM_READ_ONLY,
  admin: TEAM_READ_ONLY,
}

/**
 * Shared `teamId` column. `immutable` stops a row being moved to another
 * team after creation; `required` stops a row with no team (which nobody
 * but its creator could ever read).
 */
const teamIdColumn = {
  name: 'teamId',
  storage: 'text',
  interpretation: 'plain',
  required: true,
  immutable: true,
} as const

/** Team roles (team_members.role). Use these instead of bare strings. */
export const TEAM_ROLE = { owner: 'owner', admin: 'admin', member: 'member' } as const
export type TeamRole = (typeof TEAM_ROLE)[keyof typeof TEAM_ROLE]
export const TEAM_ROLES = [TEAM_ROLE.owner, TEAM_ROLE.admin, TEAM_ROLE.member] as const

export const INVITE_STATUSES = ['pending', 'accepted', 'declined', 'revoked'] as const
export type InviteStatus = (typeof INVITE_STATUSES)[number]

export const DECISION_STATUSES = ['open', 'closed'] as const
export type DecisionStatus = (typeof DECISION_STATUSES)[number]

export const STANCES = ['for', 'against'] as const
export type Stance = (typeof STANCES)[number]

/** draft = generated by a member while voting is open; final = written by the closing job. */
export const MEMO_KINDS = ['draft', 'final'] as const
export type MemoKind = (typeof MEMO_KINDS)[number]

/** pending = closed, memo/deliveries still to do; done = nothing left for the closing job. */
export const FINALIZE_STATES = ['pending', 'done'] as const
export type FinalizeState = (typeof FINALIZE_STATES)[number]

export const DELIVERY_CHANNELS = ['email'] as const
export type DeliveryChannel = (typeof DELIVERY_CHANNELS)[number]

/**
 * sending = claimed by a closing-job run; sent = delivered; skipped = not
 * configured (no Gmail connection), never retried; failed =
 * retried on later runs until the attempt cap.
 */
export const DELIVERY_STATUSES = ['sending', 'sent', 'skipped', 'failed'] as const
export type DeliveryStatus = (typeof DELIVERY_STATUSES)[number]

/** A team. `teamId` equals the row's own record id (set by createTeam). */
export const teamsSchema: CollectionSchema = {
  name: 'teams',
  columns: [
    teamIdColumn,
    { name: 'name', storage: 'text', interpretation: 'plain', required: true, maxLength: 80 },
    { name: 'description', storage: 'text', interpretation: 'plain', maxLength: 500 },
    // Secret for the shareable invite link (/join/<token>). Empty = no link.
    // Readable by team members (who may share it anyway); written only by the
    // createInviteLink / disableInviteLink actions (owner/admin).
    { name: 'inviteToken', storage: 'text', interpretation: 'plain', maxLength: 100 },
  ],
  teamField: 'teamId',
  permissions: teamScoped,
}

/** Membership. The `'team'` permission level reads this collection by name. */
export const teamMembersSchema: CollectionSchema = {
  name: 'team_members',
  columns: [
    teamIdColumn,
    { name: 'userId', storage: 'text', interpretation: 'plain', required: true, immutable: true },
    {
      name: 'role',
      storage: 'text',
      interpretation: { kind: 'select', options: [...TEAM_ROLES] },
      required: true,
    },
    { name: 'status', storage: 'text', interpretation: 'plain', default: 'active' },
  ],
  uniqueOn: ['teamId', 'userId'],
  teamField: 'teamId',
  permissions: teamScoped,
}

/**
 * Pending invitations by email. Team members can see their team's invites;
 * the invitee (not yet a member) reaches theirs through the listMyInvites /
 * acceptInvite / declineInvite actions, which match on the caller's email.
 */
export const teamInvitesSchema: CollectionSchema = {
  name: 'team_invites',
  columns: [
    teamIdColumn,
    { name: 'email', storage: 'text', interpretation: { kind: 'email' }, required: true, maxLength: 254 },
    {
      name: 'role',
      storage: 'text',
      interpretation: { kind: 'select', options: ['admin', 'member'] },
      required: true,
    },
    {
      name: 'status',
      storage: 'text',
      interpretation: { kind: 'select', options: [...INVITE_STATUSES] },
      required: true,
    },
    { name: 'teamName', storage: 'text', interpretation: 'plain', maxLength: 80 },
    { name: 'invitedBy', storage: 'text', interpretation: 'plain' },
  ],
  teamField: 'teamId',
  permissions: teamScoped,
}

export const decisionsSchema: CollectionSchema = {
  name: 'decisions',
  columns: [
    teamIdColumn,
    { name: 'title', storage: 'text', interpretation: 'plain', required: true, maxLength: 200 },
    { name: 'description', storage: 'text', interpretation: 'plain', maxLength: 4000 },
    { name: 'deadline', storage: 'text', interpretation: { kind: 'datetime' }, required: true },
    {
      name: 'status',
      storage: 'text',
      interpretation: { kind: 'select', options: [...DECISION_STATUSES] },
      required: true,
    },
    // 1 = members may back several options (approval voting). Unset on rows
    // from before this column existed, which read as single-choice.
    // Read it with allowsMultipleChoices() (src/lib/decision-status.ts).
    { name: 'allowMultiple', storage: 'number', interpretation: { kind: 'boolean' }, immutable: true },
    // Written by the closing job (src/server/finalize.ts). Unset while open.
    { name: 'closedAt', storage: 'text', interpretation: { kind: 'datetime' } },
    {
      name: 'finalizeState',
      storage: 'text',
      interpretation: { kind: 'select', options: [...FINALIZE_STATES] },
    },
    // Failed final-memo generations; after a few the job falls back to a
    // tally-only memo so delivery isn't blocked forever on the AI.
    { name: 'finalizeAttempts', storage: 'number', interpretation: 'plain' },
  ],
  teamField: 'teamId',
  permissions: teamScoped,
}

export const optionsSchema: CollectionSchema = {
  name: 'options',
  columns: [
    teamIdColumn,
    { name: 'decisionId', storage: 'text', interpretation: 'plain', required: true, immutable: true },
    { name: 'title', storage: 'text', interpretation: 'plain', required: true, maxLength: 200 },
    { name: 'description', storage: 'text', interpretation: 'plain', maxLength: 1000 },
    { name: 'position', storage: 'number', interpretation: 'plain' },
  ],
  teamField: 'teamId',
  permissions: teamScoped,
}

/**
 * A member's vote on a decision: one row per member per decision, holding
 * their whole selection. `optionId` is the first choice (all there was before
 * multi-choice); `optionIds` is the full list. Read with voteOptionIds().
 */
export const votesSchema: CollectionSchema = {
  name: 'votes',
  columns: [
    teamIdColumn,
    { name: 'decisionId', storage: 'text', interpretation: 'plain', required: true, immutable: true },
    { name: 'optionId', storage: 'text', interpretation: 'plain', required: true },
    { name: 'optionIds', storage: 'text', interpretation: { kind: 'json' } },
    { name: 'userId', storage: 'text', interpretation: 'plain', required: true, immutable: true },
  ],
  uniqueOn: ['decisionId', 'userId'],
  teamField: 'teamId',
  permissions: teamScoped,
}

/** Structured for/against arguments on an option; written by Day 2's action. */
export const argumentsSchema: CollectionSchema = {
  name: 'arguments',
  columns: [
    teamIdColumn,
    { name: 'decisionId', storage: 'text', interpretation: 'plain', required: true, immutable: true },
    { name: 'optionId', storage: 'text', interpretation: 'plain', required: true, immutable: true },
    { name: 'userId', storage: 'text', interpretation: 'plain', required: true, immutable: true },
    {
      name: 'stance',
      storage: 'text',
      interpretation: { kind: 'select', options: [...STANCES] },
      required: true,
    },
    { name: 'content', storage: 'text', interpretation: 'plain', required: true, maxLength: 2000 },
  ],
  teamField: 'teamId',
  permissions: teamScoped,
}

/**
 * The AI decision memo: one row per decision (uniqueOn), replaced on each
 * regeneration. Team-readable, so every open decision page sees a new memo
 * live. Written only by the memo route and the closing job.
 */
export const decisionMemosSchema: CollectionSchema = {
  name: 'decision_memos',
  columns: [
    teamIdColumn,
    { name: 'decisionId', storage: 'text', interpretation: 'plain', required: true, immutable: true },
    { name: 'content', storage: 'text', interpretation: 'plain', required: true, maxLength: 20000 },
    {
      name: 'kind',
      storage: 'text',
      interpretation: { kind: 'select', options: [...MEMO_KINDS] },
      required: true,
    },
    // userId of the member who generated it, or 'system' for the closing job.
    { name: 'generatedBy', storage: 'text', interpretation: 'plain', required: true },
    { name: 'generatedAt', storage: 'text', interpretation: { kind: 'datetime' }, required: true },
    // Model id, or 'none' when the memo was built without AI (empty discussion / fallback).
    { name: 'model', storage: 'text', interpretation: 'plain' },
    // What the memo was based on, so the page can say when it's out of date.
    { name: 'voteCount', storage: 'number', interpretation: 'plain' },
    { name: 'argumentCount', storage: 'number', interpretation: 'plain' },
  ],
  uniqueOn: ['decisionId'],
  teamField: 'teamId',
  permissions: teamScoped,
}

/**
 * Delivery record for the final memo, one row per decision and channel.
 * uniqueOn makes creating the row a claim: two overlapping job runs can't
 * both start the same delivery.
 */
export const memoDeliveriesSchema: CollectionSchema = {
  name: 'memo_deliveries',
  columns: [
    teamIdColumn,
    { name: 'decisionId', storage: 'text', interpretation: 'plain', required: true, immutable: true },
    {
      name: 'channel',
      storage: 'text',
      interpretation: { kind: 'select', options: [...DELIVERY_CHANNELS] },
      required: true,
      immutable: true,
    },
    {
      name: 'status',
      storage: 'text',
      interpretation: { kind: 'select', options: [...DELIVERY_STATUSES] },
      required: true,
    },
    { name: 'attempts', storage: 'number', interpretation: 'plain' },
    // When the current attempt started; lets a later run spot a stuck claim.
    { name: 'claimedAt', storage: 'text', interpretation: { kind: 'datetime' } },
    { name: 'sentAt', storage: 'text', interpretation: { kind: 'datetime' } },
    // Short, user-safe reason for skipped/failed (never a token or raw payload).
    { name: 'detail', storage: 'text', interpretation: 'plain', maxLength: 500 },
  ],
  uniqueOn: ['decisionId', 'channel'],
  teamField: 'teamId',
  permissions: teamScoped,
}

export const councilSchemas: CollectionSchema[] = [
  teamsSchema,
  teamMembersSchema,
  teamInvitesSchema,
  decisionsSchema,
  optionsSchema,
  votesSchema,
  argumentsSchema,
  decisionMemosSchema,
  memoDeliveriesSchema,
]

/*
 * Row shapes, as the client sees them under `record.data`. useQuery returns
 * envelopes: { recordId, data, createdBy, createdAt, updatedAt }.
 * Keep these in sync with the columns above.
 */
export interface Team { teamId: string; name: string; description?: string; inviteToken?: string }
export interface TeamMember { teamId: string; userId: string; role: TeamRole; status?: string }
export interface TeamInvite {
  teamId: string
  email: string
  role: Exclude<TeamRole, 'owner'>
  status: InviteStatus
  teamName?: string
  invitedBy?: string
}
export interface Decision {
  teamId: string
  title: string
  description?: string
  deadline: string
  status: DecisionStatus
  /** Stored as 1/0; use allowsMultipleChoices(). */
  allowMultiple?: boolean | number
  closedAt?: string
  finalizeState?: FinalizeState
  finalizeAttempts?: number
}
export interface DecisionOption {
  teamId: string
  decisionId: string
  title: string
  description?: string
  position: number
}
export interface Vote {
  teamId: string
  decisionId: string
  /** First choice. */
  optionId: string
  /** Full selection, in option order. Absent on votes from before multi-choice. */
  optionIds?: string[]
  userId: string
}
export interface Argument {
  teamId: string
  decisionId: string
  optionId: string
  userId: string
  stance: Stance
  content: string
}
export interface DecisionMemo {
  teamId: string
  decisionId: string
  content: string
  kind: MemoKind
  generatedBy: string
  generatedAt: string
  model?: string
  voteCount?: number
  argumentCount?: number
}
export interface MemoDelivery {
  teamId: string
  decisionId: string
  channel: DeliveryChannel
  status: DeliveryStatus
  attempts?: number
  claimedAt?: string
  sentAt?: string
  detail?: string
}
